// Regenerates client/src/ui/icons.js from the bootstrap-icons package (only the icons listed here).
//   npm i -D bootstrap-icons --prefix client && node scripts/build-icons.js
const fs = require('fs'); const path = require('path');
const NAMES = `house-door truck basket wallet2 graph-up-arrow shop people bell grid gear person-circle box-arrow-right plus-lg x-lg check2
check2-circle check2-all trash pencil search funnel download printer lightbulb arrow-up-right arrow-down-right exclamation-octagon-fill
exclamation-triangle-fill info-circle-fill exclamation-circle check-circle check-circle-fill circle lock-fill camera paperclip eye eye-slash
cash-coin whatsapp calendar2-check calendar-check box-seam arrow-left-right tags receipt cart-check cart-plus basket2 person-vcard journal-minus
journal-text check2-square droplet-half thermometer-half bug moisture flower1 arrow-repeat grid-3x3 house person-badge cash-stack wallet piggy-bank
bank arrow-return-left tools folder2-open building map graph-up key box-arrow-in-right geo-alt person fingerprint door-open incognito translate
chevron-right chevron-left chevron-down alarm calculator x-octagon emoji-smile inbox lock hourglass-split box-arrow-up person-plus envelope
star-fill shield-check lightning-charge list-check megaphone speedometer2 clipboard-data arrow-right play-circle telephone cloud-check
phone rocket-takeoff three-dots sliders arrow-clockwise copy share`.split(/\s+/).filter(Boolean);
const dir = path.join(__dirname, '..', 'client', 'node_modules', 'bootstrap-icons', 'icons');
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
}
fs.writeFileSync(path.join(__dirname, '..', 'client', 'src', 'ui', 'icons.js'),
  '// Bootstrap Icons (MIT) - inline SVG paths, generated by scripts/build-icons.js\nexport default ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log(Object.keys(out).length, 'icons');
